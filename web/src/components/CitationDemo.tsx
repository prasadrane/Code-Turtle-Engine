'use client';

import React, { useState } from 'react';
import Link from 'next/link';
import fixture from '@/data/citation-demo.json';
import type { GuardResult, ReviewFinding } from '@/lib/types';
import { SiteHeader } from './SiteHeader';
import { TrustAuditVisualizer } from './TrustAuditVisualizer';
import styles from './CitationDemo.module.css';

interface DemoReport {
  evidenceCategory: string; limitations: string; fixtureSha256: string;
  sources: { path: string; text: string }[];
  original: ReviewFinding[];
  outcome: { keptFindings: ReviewFinding[]; audit: GuardResult[] };
}
const report = fixture as DemoReport;
const explanations = [
  'The declared int overload exists. Its name also appears in facts extracted from Changed.Review. This does not establish a defect or prove that this overload is called there.',
  'Run exists, but Run(bool) does not match a declared signature. Strip removes this finding because no citation survives.',
  'DoesNotExist resolves to no member. Strip removes the finding; its original suggestion remains in the audit.',
  'Unrelated exists and survives the existence policy. Its name is absent from the changed member’s extracted facts. A surviving citation does not establish relevance.',
  'Run exists with two overloads. This citation names neither signature; it must not be presented as an exact overload match.',
];

export function CitationDemo() {
  const [selected, setSelected] = useState(0);
  const finding = report.original[selected];
  const audit = report.outcome.audit.filter(item => finding.citedSymbolFqns.includes(item.citedFqn));
  const retained = report.outcome.keptFindings.find(item => item.title === finding.title);
  return <><SiteHeader /><main className={`page-width ${styles.main}`}>
    <span className="eyebrow">COMPILER EVIDENCE, IN FIVE CASES</span>
    <h1 className={styles.title}>A real name can still support a bad review.</h1>
    <p className={styles.lead}>Explore what the citation guard accepts, rejects, and leaves unverified.</p>
    <p className={styles.notice}><strong>Authored fixture · no model calls.</strong> This saved playback was generated by Roslyn and the shipped guard. It demonstrates policy, not measured model accuracy.</p>
    <div className={styles.cases} role="group" aria-label="Citation cases">
      {report.original.map((item, index) => <button key={item.title} aria-pressed={selected === index}
        onClick={() => setSelected(index)}>{index + 1}. {item.title}</button>)}
    </div>
    <section aria-live="polite" aria-atomic="true" className={styles.case}>
      <h2>{finding.title}</h2><p>{explanations[selected]}</p>
      <div className={styles.comparison}>
        <article><span className="eyebrow">ORIGINAL AUTHORED SUGGESTION</span><p>{finding.detail}</p>
          <code>{finding.citedSymbolFqns.join(', ')}</code><p>Claimed location: {finding.location} · unverified</p></article>
        <article><span className="eyebrow">AFTER STRIP</span><h3>{retained ? 'Retained with limited evidence' : 'Removed'}</h3>
          <p>{retained ? 'Citation passed the declared existence/signature policy. Recommendation correctness remains unverified.' : 'All cited symbols failed this check. This finding is absent from the final review.'}</p></article>
      </div>
      <TrustAuditVisualizer guardAudit={audit} />
    </section>
    <section className={styles.source}><h2>Inspect the fixture</h2><p>Changed.cs is the selected changed file; Dependency.cs supplies compilation context.</p>
      <div className={styles.comparison}>{report.sources.map(source => <article key={source.path}><h3>{source.path}</h3><pre><code>{source.text}</code></pre></article>)}</div>
    </section>
    <footer className={styles.footer}><p>{report.limitations}</p><p>Source fixture SHA-256: <code>{report.fixtureSha256}</code></p>
      <a href="https://github.com/prasadrane/Code-Turtle-Engine/blob/main/docs/RECRUITER_DEMO.md">Reproduce locally and inspect evidence</a> · <Link href="/">Return to the review workspace</Link>
    </footer>
  </main></>;
}
